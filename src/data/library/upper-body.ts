const DEG = Math.PI / 180;

/**
 * Straight body from the ankles (planks, push-ups, inverted rows): the pelvis
 * position for a torso angle when the ankles stay at (ax, ay).
 */
const plankHip = (ax: number, ay: number, torso: number): [number, number] => [
  ax + 91 * Math.sin(torso * DEG),
  ay - 91 * Math.cos(torso * DEG),
];

/** Straight-body pose (legs in line with the torso) pinned at the ankles. */
const plankPose = (ax: number, ay: number, torso: number, arms: [LimbSpec] | [LimbSpec, LimbSpec], foot = 72): Pose => ({
  hip: plankHip(ax, ay, torso),
  torso,
  arms,
  legs: [straightLegBack(-torso, foot)],
});

